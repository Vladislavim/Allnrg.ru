const fs = require('fs');
const path = require('path');

const root = __dirname;
const touched = new Set();
let noindexRemoved = 0;
let textChanges = 0;
let linkFixes = 0;

const htmlFiles = fs.readdirSync(root).filter((file) => file.endsWith('.html'));

function replaceAll(file, replacements) {
  const full = path.join(root, file);
  let html = fs.readFileSync(full, 'utf8');
  const before = html;
  for (const [from, to] of replacements) {
    const next = html.replace(from, (...args) => {
      textChanges += 1;
      return typeof to === 'function' ? to(...args) : to;
    });
    html = next;
  }
  if (html !== before) {
    fs.writeFileSync(full, html, 'utf8');
    touched.add(file);
  }
}

for (const file of htmlFiles) {
  const full = path.join(root, file);
  let html = fs.readFileSync(full, 'utf8');
  const before = html;
  html = html.replace(/\s*<meta\s+name=["']robots["']\s+content=["']noindex,nofollow,noarchive,nosnippet["']\s*>\s*/gi, () => {
    noindexRemoved += 1;
    return '\n';
  });
  html = html.replace(/href="([^"]+\.html)"\.html"/g, (_, href) => {
    linkFixes += 1;
    return `href="${href}"`;
  });
  html = html.replace(/href="index\.html"([a-z0-9_-]+)"/gi, (_, anchor) => {
    linkFixes += 1;
    return `href="/#${anchor}"`;
  });
  if (html !== before) {
    fs.writeFileSync(full, html, 'utf8');
    touched.add(file);
  }
}

